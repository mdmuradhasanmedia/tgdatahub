    <script>
      // Table data storage
      let tableData = {
        headers: [],
        rows: []
      };

      // Initialize
      function initTable() {
        const cols = parseInt(document.getElementById('numCols').value);
        const rows = parseInt(document.getElementById('numRows').value);
        
        tableData.headers = Array(cols).fill('').map((_, i) => `Header ${i + 1}`);
        tableData.rows = Array(rows).fill(null).map((_, i) => 
          Array(cols).fill('').map((_, j) => `Cell ${i + 1}-${j + 1}`)
        );
        
        updateTable();
      }

      // Update table preview and code
      function updateTable() {
        const cols = parseInt(document.getElementById('numCols').value);
        const rows = parseInt(document.getElementById('numRows').value);
        const textAlign = document.getElementById('textAlign').value;
        const padding = document.getElementById('cellPadding').value;
        const tableWidth = document.getElementById('tableWidth').value;
        const borderWidth = document.getElementById('borderWidth').value;
        const borderStyle = document.getElementById('borderStyle').value;
        const borderCollapse = document.getElementById('borderCollapse').checked;
        const stripedRows = document.getElementById('stripedRows').checked;
        const hoverEffect = document.getElementById('hoverEffect').checked;
        
        const headerBgColor = document.getElementById('headerBgColor').value;
        const headerTextColor = document.getElementById('headerTextColor').value;
        const bodyBgColor = document.getElementById('bodyBgColor').value;
        const bodyTextColor = document.getElementById('bodyTextColor').value;
        const borderColor = document.getElementById('borderColor').value;

        // Adjust data arrays if dimensions changed
        if (tableData.headers.length !== cols) {
          if (cols > tableData.headers.length) {
            const diff = cols - tableData.headers.length;
            tableData.headers.push(...Array(diff).fill('').map((_, i) => `Header ${tableData.headers.length + i + 1}`));
            tableData.rows.forEach(row => {
              row.push(...Array(diff).fill(''));
            });
          } else {
            tableData.headers = tableData.headers.slice(0, cols);
            tableData.rows.forEach(row => row.length = cols);
          }
        }

        if (tableData.rows.length !== rows) {
          if (rows > tableData.rows.length) {
            const diff = rows - tableData.rows.length;
            for (let i = 0; i < diff; i++) {
              tableData.rows.push(Array(cols).fill(''));
            }
          } else {
            tableData.rows = tableData.rows.slice(0, rows);
          }
        }

        // Generate table HTML
        let tableStyle = `width: ${tableWidth}%; border-collapse: ${borderCollapse ? 'collapse' : 'separate'}; border: ${borderWidth}px ${borderStyle} ${borderColor};`;
        let html = `<table style="${tableStyle}">\n  <thead>\n    <tr>`;
        
        tableData.headers.forEach((header, i) => {
          const headerStyle = `background-color: ${headerBgColor}; color: ${headerTextColor}; padding: ${padding}px; border: ${borderWidth}px ${borderStyle} ${borderColor}; text-align: ${textAlign}; cursor: text;`;
          html += `\n      <th contenteditable="true" data-type="header" data-index="${i}" style="${headerStyle}">${header || ''}</th>`;
        });
        
        html += '\n    </tr>\n  </thead>\n  <tbody>';
        
        tableData.rows.forEach((row, rowIndex) => {
          html += '\n    <tr>';
          row.forEach((cell, colIndex) => {
            let cellStyle = `padding: ${padding}px; border: ${borderWidth}px ${borderStyle} ${borderColor}; text-align: ${textAlign}; color: ${bodyTextColor}; cursor: text;`;
            
            if (stripedRows && rowIndex % 2 === 1) {
              cellStyle += ` background-color: #f8fafc;`;
            } else {
              cellStyle += ` background-color: ${bodyBgColor};`;
            }
            
            html += `\n      <td contenteditable="true" data-type="body" data-row="${rowIndex}" data-col="${colIndex}" style="${cellStyle}">${cell || ''}</td>`;
          });
          html += '\n    </tr>';
        });
        
        html += '\n  </tbody>\n</table>';

        // Add hover effect CSS if enabled
        if (hoverEffect) {
          html = `<style>\ntable tr:hover td { background-color: #e0e7ff !important; }\n</style>\n` + html;
        }

        // Update preview
        document.getElementById('tablePreview').innerHTML = html;
        
        // Add event listeners for inline editing
        addCellEditListeners();
        
        // Update code display (without contenteditable attributes)
        const cleanHtml = html.replace(/\scontenteditable="true"/g, '')
                             .replace(/\sdata-type="[^"]+"/g, '')
                             .replace(/\sdata-index="[^"]+"/g, '')
                             .replace(/\sdata-row="[^"]+"/g, '')
                             .replace(/\sdata-col="[^"]+"/g, '')
                             .replace(/cursor: text;/g, '');
        document.getElementById('htmlCode').textContent = cleanHtml;
      }

      // Add event listeners for inline cell editing
      function addCellEditListeners() {
        const cells = document.querySelectorAll('#tablePreview [contenteditable="true"]');
        
        cells.forEach(cell => {
          // Update data on blur (when user clicks outside)
          cell.addEventListener('blur', function() {
            const type = this.getAttribute('data-type');
            const content = this.textContent.trim();
            
            if (type === 'header') {
              const index = parseInt(this.getAttribute('data-index'));
              tableData.headers[index] = content;
            } else {
              const row = parseInt(this.getAttribute('data-row'));
              const col = parseInt(this.getAttribute('data-col'));
              tableData.rows[row][col] = content;
            }
            
            // Update only the code, not the preview to avoid losing focus
            updateCodeOnly();
          });

          // Handle Enter key to move to next cell
          cell.addEventListener('keydown', function(e) {
            if (e.key === 'Enter' && !e.shiftKey) {
              e.preventDefault();
              this.blur();
            }
          });
        });
      }

      // Update only the HTML code display without refreshing preview
      function updateCodeOnly() {
        const cols = parseInt(document.getElementById('numCols').value);
