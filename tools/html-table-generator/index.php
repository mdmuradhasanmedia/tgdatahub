        const borderStyle = document.getElementById('borderStyle').value;
        const borderCollapse = document.getElementById('borderCollapse').checked;
        const stripedRows = document.getElementById('stripedRows').checked;
        const hoverEffect = document.getElementById('hoverEffect').checked;
        
        const headerBgColor = document.getElementById('headerBgColor').value;
        const headerTextColor = document.getElementById('headerTextColor').value;
        const bodyBgColor = document.getElementById('bodyBgColor').value;
        const bodyTextColor = document.getElementById('bodyTextColor').value;
        const borderColor = document.getElementById('borderColor').value;

        let tableStyle = `width: ${tableWidth}%; border-collapse: ${borderCollapse ? 'collapse' : 'separate'}; border: ${borderWidth}px ${borderStyle} ${borderColor};`;
        let html = `<table style="${tableStyle}">\n  <thead>\n    <tr>`;
        
        tableData.headers.forEach(header => {
          const headerStyle = `background-color: ${headerBgColor}; color: ${headerTextColor}; padding: ${padding}px; border: ${borderWidth}px ${borderStyle} ${borderColor}; text-align: ${textAlign};`;
          html += `\n      <th style="${headerStyle}">${header || '&nbsp;'}</th>`;
        });
        
        html += '\n    </tr>\n  </thead>\n  <tbody>';
        
        tableData.rows.forEach((row, rowIndex) => {
          html += '\n    <tr>';
          row.forEach(cell => {
            let cellStyle = `padding: ${padding}px; border: ${borderWidth}px ${borderStyle} ${borderColor}; text-align: ${textAlign}; color: ${bodyTextColor};`;
            
            if (stripedRows && rowIndex % 2 === 1) {
              cellStyle += ` background-color: #f8fafc;`;
            } else {
              cellStyle += ` background-color: ${bodyBgColor};`;
            }
            
            html += `\n      <td style="${cellStyle}">${cell || '&nbsp;'}</td>`;
          });
          html += '\n    </tr>';
        });
        
        html += '\n  </tbody>\n</table>';

        if (hoverEffect) {
          html = `<style>\ntable tr:hover td { background-color: #e0e7ff !important; }\n</style>\n` + html;
        }

        document.getElementById('htmlCode').textContent = html;
      }

